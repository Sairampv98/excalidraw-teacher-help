/**
 * The skills (D-447): short, separate lessons for a model on how to use the
 * whiteboard well - the way of working, what to do when it cannot see, the flow
 * charts, the animation, the page of a lesson, three voices to teach in, and the
 * teacher's method for a data structure.
 *
 * Each skill is written once, here. The server serves it as a resource, the
 * files under `skill/<name>/SKILL.md` are made from it (scripts/buildMcpSkill.mjs)
 * and a test fails when a skill names a tool that does not exist.
 */

export type Skill = {
  /** the name it is loaded under, and the folder of its file */
  name: string;
  /** when it is the right one to load: one or two sentences */
  description: string;
  /** the text of the skill, a line each */
  body: readonly string[];
};

/** where a skill is served from */
export const skillUri = (name: string) => `excalidraw://skills/${name}`;

