/** the file of a skill: the name and the description, then the text */
export const skillFile = (skill: Skill): string =>
  [
    "---",
    `name: ${skill.name}`,
    `description: ${skill.description}`,
    "---",
    "",
    ...skill.body,
    "",
  ].join("\n");

export const skillByName = (name: string): Skill | undefined =>
  SKILLS.find((skill) => skill.name === name);
