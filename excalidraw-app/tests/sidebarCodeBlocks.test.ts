import { describe, expect, it } from "vitest";

import { renderMarkdown } from "../sidebar/sidebarFiles";

describe("renderMarkdown code blocks", () => {
  it("gives every fenced block its own copy button", async () => {
    const html = await renderMarkdown(
      ["```ts", "const a = 1;", "```", "", "```py", "b = 2", "```"].join("\n"),
    );

    const blocks = html.match(/class="app-doc-codeblock"/g) ?? [];
    expect(blocks).toHaveLength(2);

    // one button per block, and it sits inside the block it belongs to. The
    // wrapper may carry a `data-language`; the button still comes first.
    expect(html.match(/class="app-doc-copy-code"/g) ?? []).toHaveLength(2);
    expect(html).toMatch(
      /<div class="app-doc-codeblock"[^>]*><button[^>]*class="app-doc-copy-code"/,
    );
  });

  it("records each block's language on the wrapper", async () => {
    // a highlighted block's `<pre>` is shiki's own output and carries no
    // `language-*` class, so the wrapper is the only place the copy handler can
    // read the fence's language from
    const html = await renderMarkdown(
      ["```python", "x = 1", "```", "", "```", "no language", "```"].join("\n"),
    );

    expect(html).toContain('data-language="python"');
    // a bare fence has nothing to record, so the attribute is left off
    expect(html).toContain('<div class="app-doc-codeblock">');
  });

  it("labels the button for assistive tech, not just the dot", async () => {
    const html = await renderMarkdown(
      ["```ts", "const a = 1;", "```"].join("\n"),
    );

    expect(html).toContain('title="Copy code"');
    expect(html).toContain('aria-label="Copy code"');
    expect(html).toContain(">Copy code</span>");
  });

  it("adds the button to a fence that could not be highlighted too", async () => {
    // a language this shiki build does not know falls back to escaped plain text
    const html = await renderMarkdown(
      ["```not-a-real-language", "raw < text", "```"].join("\n"),
    );

    expect(html).toContain('class="app-doc-codeblock"');
    expect(html).toContain('class="app-doc-copy-code"');
    expect(html).toContain("&lt;");
  });

  it("never lets a document smuggle its own copy button", async () => {
    // the button is generated by the renderer; raw HTML in the source is escaped
    const html = await renderMarkdown(
      ['<button class="app-doc-copy-code">nope</button>'].join("\n"),
    );

    expect(html).not.toContain('class="app-doc-copy-code"');
    expect(html).toContain("&lt;button");
  });

  it("keeps the code verbatim next to the button", async () => {
    const source = ["```ts", "const a = 1 < 2;", "```"].join("\n");
    const html = await renderMarkdown(source);

    // the button's own label must not bleed into the block's code text, which
    // the copy handler reads back from the <pre>
    const pre = /<pre[^>]*>([\s\S]*?)<\/pre>/.exec(html);
    expect(pre).not.toBe(null);
    expect(pre?.[1]).not.toContain("Copy code");
    expect(html.replace(/<[^>]*>/g, "")).toContain("const a = 1");
  });

  it("keeps the copy button a sibling of the <pre>, so clipping the pre is safe", async () => {
    // The markdown body clips each `pre` (`overflow: hidden`) to stop a long
    // line escaping the sidebar panel. That is only safe because the button is
    // anchored to the wrapping `.app-doc-codeblock`, not to the `pre` — move it
    // inside and the button disappears with the first long line.
    const html = await renderMarkdown(
      ["```ts", "const a = 1;", "```"].join("\n"),
    );

    const root = document.createElement("div");
    root.innerHTML = html;

    const button = root.querySelector(".app-doc-copy-code")!;

    expect(button.closest("pre")).toBeNull();
    expect(button.parentElement?.className).toBe("app-doc-codeblock");
  });
});
